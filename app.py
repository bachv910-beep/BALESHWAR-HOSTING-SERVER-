def autodetect(pid):
    p = get_row(pid)
    if not p:
        return {"changed": False, "info": ""}
    root = fdir(p)
    root.mkdir(parents=True, exist_ok=True)
    rt, mf, pub = decide(p)
    changed = rt != p["runtime"] or int(pub) != int(p["public"] or 0)
    if changed and (pid in RUNNING or alive(p["pid"])):
        stop(p, quiet=True)
    if rt == "python" and mf:
        ensure_python_reqs(root)
    if rt == "node" and mf:
        ensure_node_pkg(root, p["slug"], mf)
    x("UPDATE projects SET runtime=?, public=?, main_file=? WHERE id=?", (rt, pub, mf, pid))
    return {"changed": changed, "info": describe(rt, mf, pub)}


def plan(p):
    """How it runs: ((cmd, cwd, main), error)."""
    if p["blocked"]:
        return None, "This project has been blocked by the admin."
    if p["runtime"] == "static":
        return None, "A website does not need to be started, it is always live."
    root = fdir(p)
    root.mkdir(parents=True, exist_ok=True)
    mf = p["main_file"] or ""
    if not (mf and (root / mf).is_file()):
        mf = find_main(root, p["runtime"])
    if not mf:
        return None, "Main file not found (app.py / main.py / index.js). Upload a file or zip first."
    if p["runtime"] == "node" and not shutil.which("node"):
        return None, "Node.js is not installed on this server. Please build this bot in Python."
    script = root / mf
    if p["command"]:
        cmd = shlex.split(p["command"])
    elif p["runtime"] == "node":
        cmd = ["node", script.name]
    else:
        cmd = [sys.executable, "-u", script.name]
    return (cmd, script.parent, mf), None


# ============ PROCESS MANAGEMENT (pty = Termux-style console) ============
def spawn(pid_, cmd, cwd, tag):
    p = get_row(pid_)
    pdir(p).mkdir(parents=True, exist_ok=True)
    lp = logpath(p)
    if lp.is_file() and lp.stat().st_size > 3_000_000:
        lp.write_text("")
    libs = str(pylibs(p))
    env = {"PATH": os.environ.get("PATH", ""), "HOME": str(pdir(p)), "PORT": str(p["port"]),
           "PYTHONUNBUFFERED": "1", "PYTHONPATH": libs, "PIP_TARGET": libs,
           "LANG": "C.UTF-8", "TERM": "xterm", "COLUMNS": "100", "LINES": "40"}
    if tag != "CMD":
        hostlog(p, f"{tag}: {' '.join(shlex.quote(c) for c in cmd)}  (PORT {p['port']})")
    master, slave = pty.openpty()
    try:
        fcntl.ioctl(slave, termios.TIOCSWINSZ, struct.pack("HHHH", 40, 100, 0, 0))

        def pre():
            os.setsid()
            try:
                fcntl.ioctl(0, termios.TIOCSCTTY, 0)
            except OSError:
                pass

        proc = subprocess.Popen(cmd, cwd=str(cwd), stdin=slave, stdout=slave, stderr=slave,
                                env=env, preexec_fn=pre, close_fds=True)
    except Exception:
        os.close(master)
        os.close(slave)
        raise
    os.close(slave)
    logf = open(lp, "ab")
    RUNNING[pid_] = {"proc": proc, "master": master}
    x("UPDATE projects SET status='running', pid=? WHERE id=?", (proc.pid, pid_))
    threading.Thread(target=pump, args=(pid_, master, proc, logf), daemon=True).start()
    if tag != "CMD":
        threading.Thread(target=banner, args=(pid_, proc), daemon=True).start()
    return proc


def pump(pid_, master, proc, logf):
    while True:
        try:
            data = os.read(master, 4096)
        except OSError:
            break
        if not data:
            break
        try:
            logf.write(data)
            logf.flush()
        except OSError:
            pass
    rc = proc.wait()
    try:
        logf.write(f"\n[HOST {datetime.now():%H:%M:%S}] ⏹ Process stopped (exit code {rc})\n".encode())
        logf.close()
    except OSError:
        pass
    e = RUNNING.get(pid_)
    if e and e["proc"] is proc:
        RUNNING.pop(pid_, None)
        x("UPDATE projects SET status='stopped', pid=NULL WHERE id=? AND pid=?", (pid_, proc.pid))
    try:
        os.close(master)
    except OSError:
        pass


def banner(pid_, proc):
    time.sleep(4)
    if proc.poll() is None:
        p = get_row(pid_)
        if p:
            label = "Bot" if p["kind"] == "bot" else "App"
            hostlog(p, f"✅ {label} is running — LIVE (PID {proc.pid})")


def start_bg(pid_, tag="START"):
    with LOCK:
        if pid_ in STARTING or pid_ in RUNNING:
            return False
        STARTING.add(pid_)
    threading.Thread(target=_start_job, args=(pid_, tag), daemon=True).start()
    return True


def _start_job(pid_, tag):
    try:
        p = get_row(pid_)
        if not p:
            return
        res, msg = plan(p)
        if msg:
            hostlog(p, "❌ " + msg)
            x("UPDATE projects SET autostart=0 WHERE id=?", (pid_,))
            return
        cmd, cwd, mf = res
        x("UPDATE projects SET main_file=? WHERE id=?", (mf, pid_))
        p = get_row(pid_)
        with open(logpath(p), "a", encoding="utf-8") as lg:
            install_deps(p, fdir(p), cwd, lg)
        if pid_ in CANCEL:
            hostlog(p, "⏹ Start cancelled")
            return
        spawn(pid_, cmd, cwd, tag)
    except Exception as e:
        p = get_row(pid_)
        if p:
            hostlog(p, f"❌ Start error: {e}")
    finally:
        STARTING.discard(pid_)
        CANCEL.discard(pid_)


def run_cmd(pid_, text):
    with LOCK:
        if pid_ in STARTING:
            return False
        STARTING.add(pid_)
    threading.Thread(target=_cmd_job, args=(pid_, text), daemon=True).start()
    return True


def _cmd_job(pid_, text):
    try:
        p = get_row(pid_)
        root = fdir(p)
        root.mkdir(parents=True, exist_ok=True)
        hostlog(p, f"$ {text}")
        spawn(pid_, ["/bin/sh", "-c", text], root, "CMD")
    except Exception as e:
        p = get_row(pid_)
        if p:
            hostlog(p, f"❌ Command error: {e}")
    finally:
        STARTING.discard(pid_)


def stop(p, quiet=False):
    pid_ = p["id"]
    if pid_ in STARTING:
        CANCEL.add(pid_)
    e = RUNNING.pop(pid_, None)
    if e:
        kill_group(e["proc"])
    elif p["pid"]:
        kill_pid(p["pid"])
    x("UPDATE projects SET status='stopped', pid=NULL, autostart=0 WHERE id=?", (pid_,))
    if not quiet:
        hostlog(p, "⏹ Stopped")


def shutdown_all():
    for e in list(RUNNING.values()):
        try:
            os.killpg(e["proc"].pid, signal.SIGTERM)
        except OSError:
            pass


atexit.register(shutdown_all)


def monitor():
    time.sleep(10)
    while True:
        try:
            for p in q("SELECT * FROM projects WHERE runtime!='static' AND autostart=1 AND blocked=0"):
                if p["id"] in STARTING or alive(p["pid"]):
                    continue
                hist = [t for t in CRASHES.get(p["id"], []) if time.time() - t < 600]
                if len(hist) >= 8:  # stop if it keeps crashing
                    x("UPDATE projects SET autostart=0, status='stopped', pid=NULL WHERE id=?", (p["id"],))
                    hostlog(p, "❌ Crashing repeatedly, auto-restart stopped. Check the logs, fix the problem and press Start.")
                    CRASHES.pop(p["id"], None)
                    continue
                hist.append(time.time())
                CRASHES[p["id"]] = hist
                start_bg(p["id"], "AUTO-RESTART")
            for p in q("SELECT * FROM projects WHERE runtime!='static' AND status='running' AND autostart=0"):
                if p["id"] not in RUNNING and not alive(p["pid"]):
                    x("UPDATE projects SET status='stopped', pid=NULL WHERE id=?", (p["id"],))
        except Exception as e:
            print("[monitor]", e)
        time.sleep(20)


