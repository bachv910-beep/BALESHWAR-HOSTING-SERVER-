@app.route("/s/<slug>/<path:path>")
def serve_static(slug, path):
    p = q("SELECT * FROM projects WHERE slug=? AND runtime='static'", (slug,), one=True)
    if not p or p["blocked"]:
        return render_template("notfound.html"), 404
    root = fdir(p)
    if not root.is_dir():
        return render_template("notfound.html", msg="This website has no files yet"), 404
    path = path.strip("/")
    if not path:
        path = site_entry(p)
        if not path:
            return render_template("notfound.html", msg="HTML page not found. Upload your files."), 404
    t = safe_path(p, path)
    if t.is_dir():
        if not (t / "index.html").is_file():
            return render_template("notfound.html"), 404
        path = path + "/index.html"
    elif not t.is_file():
        if (t.parent / (t.name + ".html")).is_file():  # /about -> about.html
            path = path + ".html"
        else:
            return render_template("notfound.html"), 404
    return hosted_headers(send_from_directory(root, path))


HOP = {"connection", "keep-alive", "transfer-encoding", "content-encoding", "content-length",
       "set-cookie", "te", "upgrade", "trailer", "access-control-allow-origin"}


@app.route("/a/<slug>/", defaults={"path": ""}, methods=["GET", "POST", "PUT", "DELETE", "PATCH", "OPTIONS"])
@app.route("/a/<slug>/<path:path>", methods=["GET", "POST", "PUT", "DELETE", "PATCH", "OPTIONS"])
def proxy(slug, path):
    p = q("SELECT * FROM projects WHERE slug=? AND public=1 AND runtime!='static'", (slug,), one=True)
    if not p or p["blocked"]:
        return render_template("notfound.html"), 404
    if not alive(p["pid"]):
        return render_template("notfound.html", msg="This app is stopped. The owner needs to press Start."), 503
    hdr = {k: v for k, v in request.headers
           if k.lower() not in ("host", "cookie", "content-length", "connection", "accept-encoding")}
    try:
        r = requests.request(request.method, f"http://127.0.0.1:{p['port']}/{path}", params=request.args,
                             headers=hdr, data=request.get_data(), allow_redirects=False, timeout=60)
    except requests.ConnectionError:
        # process is running but there is no web server (bot / script), so show the LIVE status page
        return render_template("live.html", p=p), 200
    except requests.RequestException:
        return render_template("notfound.html", msg="The app did not respond. Check the console for errors."), 504
    out = {}
    for k, v in r.headers.items():
        if k.lower() in HOP:
            continue
        if k.lower() == "location" and v.startswith("/"):
            v = f"/a/{slug}{v}"
        out[k] = v
    return hosted_headers(Response(r.content, r.status_code, out))


