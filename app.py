# ============ FILE / TYPE DETECTION ============
def find_main(root, rt):
    cands, ext = (PY_MAIN, ".py") if rt == "python" else (JS_MAIN, ".js")
    if not root.is_dir():
        return ""
    bases = [root] + [d for d in sorted(root.iterdir()) if d.is_dir() and d.name not in HIDDEN]
    for base in bases:
        for c in cands:
            if (base / c).is_file():
                return (base / c).relative_to(root).as_posix()
    files = sorted(f for f in root.glob("*" + ext) if f.is_file()) or sorted(root.glob("*/*" + ext))
    return files[0].relative_to(root).as_posix() if files else ""


def detect_entry(root):
    """HTML page: index.html, otherwise any single HTML file, otherwise the only file."""
    if not root.is_dir():
        return ""
    if (root / "index.html").is_file():
        return "index.html"
    top = sorted(f for f in root.glob("*.htm*") if f.is_file())
    if top:
        return top[0].name
    sub = sorted(f for f in root.rglob("*.htm*") if f.is_file())
    if sub:
        return sub[0].relative_to(root).as_posix()
    files = sorted(f for f in root.iterdir() if f.is_file())
    return files[0].name if len(files) == 1 else ""


def server_like(path, rx):
    try:
        return bool(rx.search(path.read_text(errors="ignore")[:300000]))
    except OSError:
        return False


def keep(root, cur, cand, ext):
    return cur if cur and cur.endswith(ext) and (root / cur).is_file() else cand


def decide(p):
    """Returns (runtime, main file, public). Decided automatically from the files."""
    root = fdir(p)
    cur = p["main_file"] or ""
    py, js = find_main(root, "python"), find_main(root, "node")
    if p["kind"] == "site":
        has_html = root.is_dir() and any(root.rglob("*.htm*"))
        if py and (not has_html or server_like(root / py, PY_SERVER)):
            return "python", keep(root, cur, py, ".py"), 1
        if js and (root / "package.json").is_file() and (not has_html or server_like(root / js, JS_SERVER)):
            return "node", keep(root, cur, js, ".js"), 1
        explicit = (p["command"] or "") if p["runtime"] == "static" else ""  # page chosen by the user
        page = explicit if explicit.lower().endswith((".html", ".htm")) and (root / explicit).is_file() else ""
        return "static", page or detect_entry(root), 1
    if py:
        return "python", keep(root, cur, py, ".py"), 0
    if js:
        return "node", keep(root, cur, js, ".js"), 0
    return "python", "", 0


