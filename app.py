def extract_zip(zpath, dest, strip_top=True):
    """Extracts the zip automatically. If everything is inside one folder, that folder is removed."""
    dest = dest.resolve()
    out = []
    with zipfile.ZipFile(zpath) as z:
        infos = [m for m in z.infolist()
                 if m.filename and not m.filename.startswith("__MACOSX") and not m.filename.endswith("/")]
        names = [m.filename for m in infos]
        tops = {n.split("/")[0] for n in names}
        strip = (tops.pop() + "/") if strip_top and len(tops) == 1 and names and all("/" in n for n in names) else ""
        for m in infos:
            rel = m.filename[len(strip):] if strip and m.filename.startswith(strip) else m.filename
            parts = [s for s in rel.replace("\\", "/").split("/") if s not in ("", ".", "..")]
            if not parts:
                continue
            t = dest.joinpath(*parts).resolve()
            if t != dest and dest not in t.parents:
                raise ValueError("Invalid path found in zip")
            t.parent.mkdir(parents=True, exist_ok=True)
            with z.open(m) as src, open(t, "wb") as dst:
                shutil.copyfileobj(src, dst)
            out.append("/".join(parts))
    return out


@app.route("/api/projects/<int:pid>/upload", methods=["POST"])
@access_required
def upload(pid):
    p = get_proj(pid)
    files = request.files.getlist("file")
    if not files:
        return err("File not found")
    root = fdir(p)
    root.mkdir(parents=True, exist_ok=True)
    dest = safe_path(p, request.form.get("dir", ""))
    dest.mkdir(parents=True, exist_ok=True)
    done, zips = [], 0
    try:
        for f in files:
            fn = safe_part(f.filename or "")
            if not fn:
                continue
            if fn.lower().endswith(".zip"):
                tmp = pdir(p) / ("up_" + os.urandom(4).hex() + ".zip")
                f.save(tmp)
                try:
                    done += extract_zip(tmp, dest, strip_top=(dest == root.resolve()))
                    zips += 1
                except zipfile.BadZipFile:
                    return err("This zip file is corrupted")
                finally:
                    tmp.unlink(missing_ok=True)
            else:
                f.save(dest / fn)
                done.append(fn)
    except (OSError, ValueError) as e:
        return err(f"Upload fail: {e}", 500)
    res = autodetect(pid)
    return jsonify(success=True, count=len(done), zips=zips, changed=res["changed"], info=res["info"])


