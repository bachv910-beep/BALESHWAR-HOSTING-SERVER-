@app.route("/api/projects/<int:pid>/input", methods=["POST"])
@access_required
def p_input(pid):
    """If a process is running, the text goes to it (password / Enter). If nothing runs, the text runs as a command."""
    p = get_proj(pid)
    d = request.get_json(silent=True) or {}
    e = RUNNING.get(pid)
    running = bool(e) and e["proc"].poll() is None
    if d.get("ctrl_c"):
        if not running:
            return err("No process is running")
        x("UPDATE projects SET autostart=0 WHERE id=?", (pid,))
        try:
            os.write(e["master"], b"\x03")
        except OSError:
            return err("The console has closed")
        return jsonify(success=True, mode="input")
    text = str(d.get("text", ""))[:2000]
    if running:
        try:
            os.write(e["master"], (text + "\n").encode())
        except OSError:
            return err("The console has closed")
        return jsonify(success=True, mode="input")
    if not text.strip():
        return err("Type a command or password")
    if p["runtime"] == "static":
        return err("Websites do not have a console")
    if p["blocked"]:
        return err("This project is blocked")
    if not run_cmd(pid, text):
        return err("Starting, please wait a moment")
    return jsonify(success=True, mode="command")


