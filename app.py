def tail(path, n=400):
    try:
        with open(path, "rb") as f:
            f.seek(0, 2)
            size = f.tell()
            f.seek(max(0, size - 150000))
            raw = f.read().decode("utf-8", "replace")
    except FileNotFoundError:
        return "Console is ready. Press Start or type a command below."
    txt = ANSI.sub("", raw).replace("\r\n", "\n")
    lines = [l.split("\r")[-1] for l in txt.split("\n")]
    return "\n".join(lines[-n:]).strip("\n") or "Console is ready."


def safe_part(s):
    s = os.path.basename(str(s or "").replace("\\", "/")).replace("\x00", "").strip()
    return "" if s in ("", ".", "..") else s[:120]


def clean_rel(s):
    parts = [safe_part(p) for p in str(s or "").replace("\\", "/").split("/")]
    return "/".join(p for p in parts if p)


def safe_path(p, rel):
    root = fdir(p).resolve()
    t = (root / str(rel or "").replace("\x00", "").strip("/")).resolve()
    if t != root and root not in t.parents:
        abort(400)
    return t


def list_dir(p, rel):
    d = safe_path(p, rel)
    if not d.is_dir():
        return []
    out = []
    for e in sorted(d.iterdir(), key=lambda e: (e.is_file(), e.name.lower())):
        if e.name in HIDDEN:
            continue
        out.append({"name": e.name, "type": "file" if e.is_file() else "dir",
                    "size": e.stat().st_size if e.is_file() else 0})
    return out


# ============ AUTO DEPENDENCIES (creates requirements.txt from your files when it is missing) ============
def scan_python(root):
    local, names, files = set(), set(), []
    for dp, dns, fns in os.walk(root):
        dns[:] = [d for d in dns if d not in HIDDEN]
        local.update(dns)
        for f in fns:
            if f.endswith(".py"):
                local.add(f[:-3])
                files.append(Path(dp, f))
    for f in files:
        try:
            if f.stat().st_size > 1_000_000:
                continue
            tree = ast.parse(f.read_text(errors="ignore"))
        except (SyntaxError, ValueError, OSError):
            continue
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                names.update(a.name.split(".")[0] for a in node.names)
            elif isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
                names.add(node.module.split(".")[0])
    out = {PY_ALIAS.get(n, n) for n in names if n.isidentifier() and n not in PY_STD and n not in local}
    return sorted(out, key=str.lower)


def req_names(text):
    out = set()
    for line in text.splitlines():
        line = line.strip()
        if line and not line.startswith(("#", "-")):
            out.add(re.split(r"[=<>!~\[;@ ]", line)[0].strip().lower())
    return out


def ensure_python_reqs(root):
    """Creates requirements.txt when it is missing. A requirements.txt written by the user is never changed."""
    req = root / "requirements.txt"
    if req.is_file() and not req.read_text(errors="ignore").startswith(REQ_HEADER):
        return req
    pkgs = scan_python(root)
    if not pkgs:
        if req.is_file():
            req.unlink()
        return None
    body = REQ_HEADER + "\n" + "\n".join(pkgs) + "\n"
    if not req.is_file() or req.read_text(errors="ignore") != body:
        req.write_text(body)
    return req


def install_python(p, root, workdir, lg):
    pdir(p).mkdir(parents=True, exist_ok=True)
    wreq = workdir / "requirements.txt"
    req = wreq if wreq.is_file() else ensure_python_reqs(root)
    text = req.read_text(errors="ignore") if req and req.is_file() else ""
    have = req_names(text)
    missing = [m for m in scan_python(root) if m.lower() not in have]
    if not text.strip() and not missing:
        return
    key = hashlib.sha256((text + "\n" + "\n".join(missing)).encode()).hexdigest()
    mk = pdir(p) / ".deps_key"
    if mk.is_file() and mk.read_text() == key and pylibs(p).is_dir():
        return
    lg.write(f"\n[HOST {datetime.now():%H:%M:%S}] Installing packages (the first time can take 1-2 minutes)...\n")
    lg.flush()
    cmd = [sys.executable, "-m", "pip", "install", "--no-input", "--disable-pip-version-check",
           "--target", str(pylibs(p))]
    if text.strip():
        cmd += ["-r", str(req)]
    cmd += missing
    try:
        ok = subprocess.run(cmd, stdout=lg, stderr=subprocess.STDOUT, cwd=str(root), timeout=900).returncode == 0
    except subprocess.TimeoutExpired:
        ok = False
    if ok:
        mk.write_text(key)
        lg.write(f"[HOST {datetime.now():%H:%M:%S}] ✅ Packages ready\n")
    else:
        lg.write(f"[HOST {datetime.now():%H:%M:%S}] ❌ Install failed (see the output above). Add the package named in the error to requirements.txt.\n")
    lg.flush()


def scan_node(root):
    names = set()
    for dp, dns, fns in os.walk(root):
        dns[:] = [d for d in dns if d not in HIDDEN]
        for f in fns:
            if not f.endswith((".js", ".mjs", ".cjs")):
                continue
            fp = Path(dp, f)
            try:
                if fp.stat().st_size > 1_000_000:
                    continue
                txt = fp.read_text(errors="ignore")
            except OSError:
                continue
            for mod in NODE_RE.findall(txt):
                if mod.startswith((".", "/", "node:")):
                    continue
                pkg = "/".join(mod.split("/")[:2]) if mod.startswith("@") else mod.split("/")[0]
                if pkg and pkg not in NODE_BUILTIN:
                    names.add(pkg)
    return sorted(names)


def ensure_node_pkg(root, slug, mf):
    pj = root / "package.json"
    deps = scan_node(root)
    if pj.is_file():
        try:
            data = json.loads(pj.read_text(errors="ignore") or "{}")
        except ValueError:
            return
        if not isinstance(data, dict) or not data.get("_vip_auto"):
            return
    else:
        if not deps:
            return
        data = {"name": slug, "version": "1.0.0", "private": True, "main": mf,
                "_vip_auto": True, "dependencies": {}}
    dep = dict(data.get("dependencies") or {})
    for d in deps:
        dep.setdefault(d, "*")
    if dep != (data.get("dependencies") or {}):
        data["dependencies"] = dep
        pj.write_text(json.dumps(data, indent=2))


def install_node(p, root, workdir, lg):
    pkgdir = workdir if (workdir / "package.json").is_file() else root
    pj = pkgdir / "package.json"
    if not pj.is_file():
        return
    pdir(p).mkdir(parents=True, exist_ok=True)
    key = hashlib.sha256(pj.read_bytes()).hexdigest()
    mk = pdir(p) / ".npm_key"
    if mk.is_file() and mk.read_text() == key and (pkgdir / "node_modules").is_dir():
        return
    if not shutil.which("npm"):
        lg.write("[HOST] npm is not available on this server, Node packages cannot be installed\n")
        lg.flush()
        return
    lg.write(f"\n[HOST {datetime.now():%H:%M:%S}] Installing Node packages...\n")
    lg.flush()
    try:
        ok = subprocess.run(["npm", "install", "--no-audit", "--no-fund"], stdout=lg,
                            stderr=subprocess.STDOUT, cwd=str(pkgdir), timeout=900).returncode == 0
    except subprocess.TimeoutExpired:
        ok = False
    if ok:
        mk.write_text(key)
        lg.write(f"[HOST {datetime.now():%H:%M:%S}] ✅ Packages ready\n")
    else:
        lg.write(f"[HOST {datetime.now():%H:%M:%S}] ❌ npm install failed (see the output above)\n")
    lg.flush()


